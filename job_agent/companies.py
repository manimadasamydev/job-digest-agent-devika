def _norm(url: str) -> str:
    parsed = urlparse(url)
    return urlunparse((parsed.scheme, parsed.netloc.lower(), parsed.path.rstrip("/"), "", "", ""))


def unique_companies() -> list[dict[str, str]]:
    seen: set[str] = set()
    out: list[dict[str, str]] = []
    for name, url in _RAW:
        key = _norm(url)
        if key in seen:
            continue
        seen.add(key)
        out.append({"name": name, "url": url})
    return out


